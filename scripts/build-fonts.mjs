/**
 * Embeds the OFL-licensed font subsets used by the CV templates into
 * src/assets/fonts.ts as base64 woff2 strings.
 *
 * Why embed instead of copying files?
 *  - The standalone print/PDF HTML must be a single self-contained document
 *    (Electron prints it from a data: URL, where no external fetch is possible).
 *  - Fonts must also be available offline on Windows 7, which does not ship a
 *    Bengali UI font with consistent metrics.
 *
 * Licence: Inter, Lora, Noto Sans Bengali and Noto Serif Bengali are all SIL
 * Open Font License 1.1 — embedding and redistribution are permitted.
 * Run: node scripts/build-fonts.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');

const FONTS = [
  { family: 'Inter', weight: 400, path: 'inter/files/inter-latin-400-normal.woff2' },
  { family: 'Inter', weight: 500, path: 'inter/files/inter-latin-500-normal.woff2' },
  { family: 'Inter', weight: 600, path: 'inter/files/inter-latin-600-normal.woff2' },
  { family: 'Inter', weight: 700, path: 'inter/files/inter-latin-700-normal.woff2' },
  { family: 'Lora', weight: 400, path: 'lora/files/lora-latin-400-normal.woff2' },
  { family: 'Lora', weight: 600, path: 'lora/files/lora-latin-600-normal.woff2' },
  { family: 'Lora', weight: 700, path: 'lora/files/lora-latin-700-normal.woff2' },
  { family: 'Noto Sans Bengali', weight: 400, path: 'noto-sans-bengali/files/noto-sans-bengali-bengali-400-normal.woff2' },
  { family: 'Noto Sans Bengali', weight: 600, path: 'noto-sans-bengali/files/noto-sans-bengali-bengali-600-normal.woff2' },
  { family: 'Noto Sans Bengali', weight: 700, path: 'noto-sans-bengali/files/noto-sans-bengali-bengali-700-normal.woff2' },
  { family: 'Noto Serif Bengali', weight: 400, path: 'noto-serif-bengali/files/noto-serif-bengali-bengali-400-normal.woff2' },
  { family: 'Noto Serif Bengali', weight: 700, path: 'noto-serif-bengali/files/noto-serif-bengali-bengali-700-normal.woff2' },
];

const entries = [];
for (const f of FONTS) {
  const abs = join(nm, '@fontsource', f.path);
  const b64 = readFileSync(abs).toString('base64');
  entries.push(
    `  { family: '${f.family}', weight: ${f.weight}, b64: '${b64}' },`,
  );
}

const header = `/**
 * AUTO-GENERATED by scripts/build-fonts.mjs — do not edit by hand.
 *
 * Base64 WOFF2 payloads for the embedded CV font set.
 * Licence: SIL Open Font License 1.1 (Inter, Lora, Noto Sans Bengali, Noto Serif Bengali).
 * Bengali coverage: Noto Sans/Serif Bengali carry the full Bengali block, so no
 * Windows 7 "square box" rendering can occur.
 */
export interface EmbeddedFont {
  family: string;
  weight: number;
  b64: string;
}

export const EMBEDDED_FONTS: EmbeddedFont[] = [
`;

const css = `
let cachedCss: string | null = null;

/** @font-face rules with data: URIs — safe inside a data: URL document. */
export function embeddedFontCss(): string {
  if (cachedCss) return cachedCss;
  cachedCss = EMBEDDED_FONTS.map(
    (f) => \`@font-face{font-family:'\${f.family}';font-style:normal;font-weight:\${f.weight};font-display:block;src:url(data:font/woff2;base64,\${f.b64}) format('woff2');}\`,
  ).join('\\n');
  return cachedCss;
}
`;

mkdirSync(join(root, 'src/assets'), { recursive: true });
writeFileSync(join(root, 'src/assets/fonts.ts'), `${header}${entries.join('\n')}\n];\n${css}`, 'utf8');
console.log(`Embedded ${FONTS.length} font faces into src/assets/fonts.ts`);
